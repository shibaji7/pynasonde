def __getattr__(name):
    if name in _LAZY:
        import importlib

        value = getattr(importlib.import_module(_LAZY[name]), name)
        globals()[name] = value
        return value
    raise AttributeError(f"module 'pynasonde' has no attribute {name!r}")


def __dir__():
    return sorted(list(globals()) + list(_LAZY))


